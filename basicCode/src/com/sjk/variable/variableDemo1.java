public class variableDemo1 {
        public static void main(String[] args) {
            double a = 0;
            double b = 10;
            double c = 20;
            System.out.println(a+b+c);

            a = a + 10 - 2;
            System.out.println(a);

            System.out.println(a+b+c);
        }
}
