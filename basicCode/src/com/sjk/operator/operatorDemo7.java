package com.sjk.operator;

public class operatorDemo7 {
    public static void main(String[] args) {
        /*
        = 赋值运算符
        += 加后赋值
        -= 减后赋值
        *= 乘后赋值
        /= 除后赋值
        %= 取模后赋值
         */

        //测试
        int a = 10;
        a += 20; //a = a + 20
        System.out.println(a);
        a -= 20; //a = a - 20
        System.out.println(a);
        a *= 20; //a = a * 20
        System.out.println(a);
        a /= 20; //a = a / 20
        System.out.println(a);
        a %= 20; //a = a % 20
        System.out.println(a);

    }
}
